/**
 * Temporary-home / profile / native-messaging plumbing for the Firefox suite.
 *
 * Security: like the Chromium harness, every run gets a fresh temp root with
 * its own HOME, profile, app socket, logs and native-messaging manifest. The
 * real user's profile and native-messaging directory are never touched.
 *
 * Firefox reads native-messaging manifests from
 *   macOS: ~/Library/Application Support/Mozilla/NativeMessagingHosts
 *   Linux: ~/.mozilla/native-messaging-hosts
 * Both locations are written (harmless on the other platform) under the temp
 * HOME. On macOS, CFFIXED_USER_HOME is set as well because Foundation ignores
 * $HOME for Application Support paths.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import {
  FIREFOX_ADDON_ID,
  NATIVE_HOST_NAME,
  NATIVE_HOST_BINARY,
} from "./config.mjs";

/** @returns {string} */
function createTempRoot() {
  const base = process.env.FP_E2E_TMPDIR || os.tmpdir();
  let root = fs.mkdtempSync(path.join(base, "friendlypass-firefox-e2e-"));
  // AF_UNIX paths are limited to ~104 bytes on macOS; the socket lives at
  // <root>/app.sock, so fall back to /tmp when the OS temp dir is deep.
  if (path.join(root, "app.sock").length > 100) {
    fs.rmSync(root, { recursive: true, force: true });
    root = fs.mkdtempSync("/tmp/fp9-");
  }
  return root;
}

/** @param {string} value */
function shellQuote(value) {
  return `"${value.replace(/(["\\$`])/g, "\\$1")}"`;
}

/**
 * @typedef {object} FirefoxEnvironment
 * @property {string} root
 * @property {string} home
 * @property {string} profile
 * @property {string} appSocket
 * @property {string} appLog
 * @property {string} hostPid
 * @property {string} hostStderr
 * @property {string} wrapper
 * @property {string[]} manifests
 */

/** @returns {FirefoxEnvironment} */
export function createEnvironment() {
  const root = createTempRoot();
  const home = path.join(root, "home");
  const profile = path.join(root, "profile");
  fs.mkdirSync(home, { recursive: true });
  fs.mkdirSync(profile, { recursive: true });

  /** @type {FirefoxEnvironment} */
  const paths = {
    root,
    home,
    profile,
    appSocket: path.join(root, "app.sock"),
    appLog: path.join(root, "app-server.jsonl"),
    hostPid: path.join(root, "host.pid"),
    hostStderr: path.join(root, "host-stderr.log"),
    wrapper: path.join(root, "friendlypass-host.sh"),
    manifests: [],
  };

  writeHostWrapper(paths);
  installNativeManifest(paths);

  fs.writeFileSync(
    path.join(root, "harness-env.json"),
    `${JSON.stringify(
      {
        home,
        profile,
        appSocket: paths.appSocket,
        hostBinary: NATIVE_HOST_BINARY,
        platform: process.platform,
      },
      null,
      2,
    )}\n`,
  );

  return paths;
}

/** @param {FirefoxEnvironment} paths */
function writeHostWrapper(paths) {
  const lines = [
    "#!/bin/sh",
    "# Generated by the WP9 Firefox e2e harness. Never installed outside the temp HOME.",
    "set -u",
    `echo $$ > ${shellQuote(paths.hostPid)}`,
    `export FP_APP_SOCKET=${shellQuote(paths.appSocket)}`,
    `export FRIENDLYPASS_BROWSER_SOCKET=${shellQuote(paths.appSocket)}`,
    `export FRIENDLYPASS_APP_SOCKET=${shellQuote(paths.appSocket)}`,
    `export FRIENDLYPASS_SOCKET=${shellQuote(paths.appSocket)}`,
    `exec ${shellQuote(NATIVE_HOST_BINARY)} 2>> ${shellQuote(paths.hostStderr)}`,
  ];
  fs.writeFileSync(paths.wrapper, `${lines.join("\n")}\n`, { mode: 0o755 });
  fs.chmodSync(paths.wrapper, 0o755);
}

/**
 * Firefox native-messaging manifests use `allowed_extensions` with the add-on
 * id from `browser_specific_settings.gecko.id`, not Chrome-style origins.
 *
 * @param {FirefoxEnvironment} paths
 */
export function installNativeManifest(paths) {
  const manifest = {
    name: NATIVE_HOST_NAME,
    description: "friendlypass Firefox e2e harness native messaging host",
    path: paths.wrapper,
    type: "stdio",
    allowed_extensions: [FIREFOX_ADDON_ID],
  };

  const dirs = [
    path.join(
      paths.home,
      "Library/Application Support/Mozilla/NativeMessagingHosts",
    ),
    path.join(paths.home, ".mozilla/native-messaging-hosts"),
  ];
  const written = [];
  for (const dir of dirs) {
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, `${NATIVE_HOST_NAME}.json`);
    fs.writeFileSync(file, `${JSON.stringify(manifest, null, 2)}\n`, {
      mode: 0o644,
    });
    written.push(file);
  }
  paths.manifests = written;
  return written;
}

/** @param {FirefoxEnvironment} paths */
export function removeEnvironment(paths) {
  if (process.env.FP_KEEP_TEMP === "1") {
    process.stderr.write(`[firefox-harness] keeping temp dir ${paths.root}\n`);
    return;
  }
  // Firefox may still flush profile files for a moment after quit; retry.
  fs.rmSync(paths.root, {
    recursive: true,
    force: true,
    maxRetries: 10,
    retryDelay: 100,
  });
}

/** Read the PID written by the generated host wrapper. */
export function readHostPid(paths) {
  try {
    const pid = Number.parseInt(fs.readFileSync(paths.hostPid, "utf8").trim(), 10);
    return Number.isFinite(pid) && pid > 0 ? pid : null;
  } catch {
    return null;
  }
}

export function isProcessAlive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error.code === "EPERM";
  }
}

/** Parse a JSONL log, tolerating a partially-written final line. */
export function readJsonl(file) {
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch {
    return [];
  }
  const entries = [];
  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    try {
      entries.push(JSON.parse(line));
    } catch {
      /* partial last line while the writer is active */
    }
  }
  return entries;
}
